# Day 13 - Tuples

student = ("Priya", 21, "Biomedical Engineering")

# Print the tuple
print("Tuple:", student)

# Access items using index
print("First item:", student[0])
print("Second item:", student[1])
print("Third item:", student[2])

# Find total number of items
print("Total items:", len(student))

# Tuple values cannot be changed
print("Tuple values cannot be changed!")