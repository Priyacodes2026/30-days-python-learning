# Day 14 - Dictionaries

student = {
    "name": "Priya",
    "age": 21,
    "course": "Biomedical Engineering"
}

# Print dictionary
print("Student:", student)

# Access values using keys
print("Name:", student["name"])
print("Age:", student["age"])
print("Course:", student["course"])

# Using get()
print("Name using get():", student.get("name"))